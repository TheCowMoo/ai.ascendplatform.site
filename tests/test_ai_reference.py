"""The AI reference must exist, link correctly and match its generated index.

Run: .\\venv\\Scripts\\python.exe tests\\test_ai_reference.py
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY = sys.executable
REQUIRED = [
    ROOT / "AGENTS.md",
    ROOT / "docs" / "ai" / "REFERENCE.md",
    ROOT / "docs" / "ai" / "RECIPES.md",
    ROOT / "docs" / "ai" / "HANDOFF.md",
    ROOT / "docs" / "ai" / "INDEX.md",
    ROOT / "tools" / "ai_reference.py",
]


def check(name, got, want=True):
    ok = got == want
    print(("ok   " if ok else "FAIL ") + name +
          ("" if ok else " - got %r want %r" % (got, want)))
    if not ok:
        raise SystemExit(1)


def test_required_files():
    for path in REQUIRED:
        check("exists: %s" % path.relative_to(ROOT), path.exists())


def test_generated_index_is_current():
    result = subprocess.run(
        [PY, "tools/ai_reference.py", "--check"], cwd=ROOT,
        capture_output=True, text=True,
    )
    check("generated index is current", result.returncode, 0)
    check("generator reports OK", "AI INDEX OK" in (result.stdout or ""), True)


def test_index_sections_and_counts():
    text = (ROOT / "docs" / "ai" / "INDEX.md").read_text(encoding="utf-8")
    check("generated marker is present",
          "Generated by tools/ai_reference.py" in text, True)
    for section in ("## Routes", "## Settings", "## Database tables",
                    "## Preflight suites", "## UI view functions"):
        check("index section: " + section, section in text, True)
    route_rows = text.count("| GET |") + text.count("| POST |") + \
        text.count("| PUT |") + text.count("| DELETE |") + text.count("| PATCH |")
    check("route inventory is non-trivial", route_rows > 100, True)
    check("settings inventory is non-trivial", text.count("| `") > 50, True)
    check("table inventory includes oauth_connections",
          "- `oauth_connections`" in text, True)


def test_agents_links_resolve():
    text = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    links = re.findall(r"\[[^\]]+\]\(([^)]+)\)", text)
    for link in links:
        if link.startswith(("http://", "https://", "#", "mailto:")):
            continue
        target = link.split("#", 1)[0]
        if target:
            check("link resolves: %s" % target, (ROOT / target).exists())
    for required in ("docs/ai/REFERENCE.md", "docs/ai/RECIPES.md",
                     "docs/ai/INDEX.md"):
        check("AGENTS mentions " + required, required in text, True)


def main():
    test_required_files()
    test_generated_index_is_current()
    test_index_sections_and_counts()
    test_agents_links_resolve()
    print("\nAI REFERENCE OK - files, links and generated index agree")


if __name__ == "__main__":
    main()
